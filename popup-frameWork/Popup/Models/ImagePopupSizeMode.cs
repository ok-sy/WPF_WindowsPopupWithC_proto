namespace Popup.Models
{
    /*
     * 이미지 팝업 크기를 결정하는 방식을 정의한다.
     */
    public enum ImagePopupSizeMode
    {
        /*
         * ADAPTIVE: 팝업 width/height가 기준이다(설계 15 확정 계약).
         * 이미지는 팝업이 배정한 영역 안에 비율을 유지해 맞춰지며,
         * imageWidth/imageHeight는 최대 표시 크기로만 쓴다.
         * 이미지 때문에 팝업 크기가 바뀌지 않는다. (과거 값 FIXED도 이 모드로 처리)
         *
         * [설계 18 L-0 — C-26] 예전 주석("이미지 비율로 가로형·세로형·정사각형용
         * 미리 정해진 팝업 크기를 사용")이 확정 계약과 달라 수정했다. 코드 동작 변화 없음.
         */
        Adaptive,

        /*
         * 불러온 이미지의 실제 표시 크기를 기준으로
         * 팝업 창의 너비와 높이를 계산한다.
         *
         * 이미지가 모니터보다 큰 경우에는
         * 화면 안에 들어오도록 자동으로 축소한다.
         */
        FitToImage
    }
}