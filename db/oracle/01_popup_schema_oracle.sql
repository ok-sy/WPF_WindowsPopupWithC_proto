COMMENT ON COLUMN QUESTION_TEMPLATE.TEMPLATE_GROUP_ID IS '템플릿 그룹. 원본 gen_random_uuid() → Oracle SUBSTR(RAWTOHEX(SYS_GUID()),1,30)';

-- 원본: CREATE UNIQUE INDEX ux_question_template_current ON question_template (template_group_id) WHERE current_yn = 'Y';
-- Oracle은 부분 인덱스가 없으므로 함수 기반 유니크 인덱스로 변환한다.
-- CURRENT_YN <> 'Y' 인 행은 NULL 키가 되어 유니크 검사 대상에서 제외된다.
CREATE UNIQUE INDEX UX_QUESTION_TEMPLATE_CURRENT
    ON QUESTION_TEMPLATE (CASE WHEN CURRENT_YN = 'Y' THEN TEMPLATE_GROUP_ID END);

