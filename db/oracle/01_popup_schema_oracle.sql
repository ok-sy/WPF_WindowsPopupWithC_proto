(
    RECEIPT_ID    NUMBER(19)         NOT NULL,
    RESULT_ID     VARCHAR2(64 CHAR)  NOT NULL,
    EMPLOYEE_NO   VARCHAR2(30 CHAR)  NOT NULL,
    POPUP_ID      VARCHAR2(50 CHAR)  NOT NULL,
    RESULT_TYPE   VARCHAR2(20 CHAR)  NOT NULL,
    RESULT_STATUS VARCHAR2(10 CHAR)  NOT NULL,
    RESULT_CODE   VARCHAR2(50 CHAR),
