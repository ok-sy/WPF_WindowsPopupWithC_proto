-- -----------------------------------------------------------------------------------------------------
-- 배경: 서버·WPF·관리자 웹에 과거·이관 데이터용 기본값 분기가 남아 있었다. L-4 코드는 이 분기를 지우므로
--       기존 DB는 **L-4 서버·WPF 배포 전에** 이 스크립트로 데이터를 맞추고 제약을 걸어야 한다.
--   1) POPUP_NOTICE.DISPLAY_MODE  : SEQUENTIAL / SIMULTANEOUS 외 값 → SEQUENTIAL, CHECK 추가
--                                   (서버 매퍼의 CASE fallback 제거 — S-14)
--   2) POPUP_NOTICE 크기 컬럼 8개 : NULL → 기존 서버 기본값(900/620/0.7/0.75/480/320/1200/900), NOT NULL
--                                   (서버 toResponseDto 기본값 제거 — S-15)
--   3) POPUP_QUESTION RATING5     : SINGLE_CHOICE + OPTION_LAYOUT HORIZONTAL로 이관, 선택지가 없으면 1~5 생성,
--                                   QUESTION_TYPE CHECK 추가 (WPF RATING5 매핑 제거 — S-17·C-25)
--   4) TEXT CONTENT_OPTIONS       : showHighlight / showBottomDescription 키가 없으면 기존 fallback 규칙으로 채움
--                                   (문구가 있으면 true) (WPF·관리자 웹의 null fallback 제거 — C-23)
-- 실행: 팝업 테이블이 있는 계정으로 SQL*Plus 실행 (NLS_LANG=KOREAN_KOREA.AL32UTF8).
--       - 로컬 XE(POPUP 계정 스키마)      : @08_legacy_data_constraints_oracle.sql POPUP.
--       - 원격 개발 DB(앱 계정 zero-rule) : @08_legacy_data_constraints_oracle.sql ""
--       전제: 05_question_option_layout_oracle.sql(OPTION_LAYOUT 컬럼) 적용 완료.
-- 여러 번 실행해도 결과가 같다(이미 있는 제약·NOT NULL은 건너뜀).
-- =====================================================================================================
SET PAGESIZE 200 LINESIZE 250 LONG 4000 TRIMSPOOL ON FEEDBACK ON DEFINE ON SERVEROUTPUT ON
DEFINE S = &1
COLUMN POPUP_ID FORMAT A24
COLUMN DISPLAY_MODE FORMAT A20
COLUMN QUESTION_TITLE FORMAT A40

