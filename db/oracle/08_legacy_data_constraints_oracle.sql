PROMPT === 3. 확인: RATING5 문항 (QUIZ 소속이면 정답 선택지를 관리자 화면에서 지정해야 재저장 가능) ===
SELECT q.QUESTION_ID, q.QUESTION_TEMPLATE_ID, q.QUESTION_TITLE,
