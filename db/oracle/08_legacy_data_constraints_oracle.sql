  FROM &S.POPUP_QUESTION q WHERE q.QUESTION_TYPE NOT IN ('SINGLE_CHOICE', 'MULTIPLE_CHOICE', 'TEXT');

PROMPT === 4. 확인: 표시 플래그가 없는 TEXT 팝업 ===
SELECT c.POPUP_ID,
       CASE WHEN DBMS_LOB.INSTR(c.CONTENT_OPTIONS, '"showHighlight":') > 0 THEN 'Y' ELSE 'N' END HAS_SHOW_HIGHLIGHT,
       CASE WHEN DBMS_LOB.INSTR(c.CONTENT_OPTIONS, '"showBottomDescription":') > 0 THEN 'Y' ELSE 'N' END HAS_SHOW_BOTTOM
  FROM &S.POPUP_CONTENT c JOIN &S.POPUP_NOTICE n ON n.POPUP_ID = c.POPUP_ID
 WHERE n.POPUP_TYPE = 'TEXT'
   AND (c.CONTENT_OPTIONS IS NULL
        OR DBMS_LOB.INSTR(c.CONTENT_OPTIONS, '"showHighlight":') = 0
        OR DBMS_LOB.INSTR(c.CONTENT_OPTIONS, '"showBottomDescription":') = 0);

