PROMPT === 7. 보정: RATING5 → 선택지 1~5 생성(선택지가 없을 때만) 후 SINGLE_CHOICE + HORIZONTAL ===
INSERT INTO &S.POPUP_OPTION (OPTION_ID, QUESTION_ID, OPTION_VALUE, OPTION_TEXT, CORRECT_YN, SORT_ORDER, CREATED_BY, UPDATED_BY)
SELECT &S.SEQ_POPUP_OPTION.NEXTVAL, x.QUESTION_ID, x.N, x.N, 'N', x.N, 'CLEANUP', 'CLEANUP'
  FROM (SELECT q.QUESTION_ID, TO_CHAR(r.N) N
          FROM &S.POPUP_QUESTION q
         CROSS JOIN (SELECT LEVEL N FROM DUAL CONNECT BY LEVEL <= 5) r
         WHERE q.QUESTION_TYPE = 'RATING5'
           AND NOT EXISTS (SELECT 1 FROM &S.POPUP_OPTION o WHERE o.QUESTION_ID = q.QUESTION_ID)) x;
UPDATE &S.POPUP_QUESTION
   SET QUESTION_TYPE = 'SINGLE_CHOICE', OPTION_LAYOUT = 'HORIZONTAL', UPDATED_BY = 'CLEANUP',
       UPDATED_AT = CAST(SYSTIMESTAMP AT TIME ZONE 'Asia/Seoul' AS TIMESTAMP)
 WHERE QUESTION_TYPE = 'RATING5';

PROMPT === 8. 보정: TEXT showHighlight / showBottomDescription 채우기 ===
UPDATE &S.POPUP_CONTENT c
   SET CONTENT_OPTIONS =
         CASE WHEN c.CONTENT_OPTIONS IS NULL OR REGEXP_LIKE(c.CONTENT_OPTIONS, '^\s*\{\s*\}\s*$')
              THEN TO_CLOB('{"showHighlight":'
                   || CASE WHEN REGEXP_LIKE(c.CONTENT_OPTIONS, '"highlightText":"\s*[^"[:space:]]') THEN 'true' ELSE 'false' END || '}')
              ELSE REGEXP_REPLACE(c.CONTENT_OPTIONS, '^\s*\{', '{"showHighlight":'
                   || CASE WHEN REGEXP_LIKE(c.CONTENT_OPTIONS, '"highlightText":"\s*[^"[:space:]]') THEN 'true' ELSE 'false' END || ',', 1, 1)
         END,
       UPDATED_BY = 'CLEANUP', UPDATED_AT = CAST(SYSTIMESTAMP AT TIME ZONE 'Asia/Seoul' AS TIMESTAMP)
 WHERE c.POPUP_ID IN (SELECT POPUP_ID FROM &S.POPUP_NOTICE WHERE POPUP_TYPE = 'TEXT')
   AND (c.CONTENT_OPTIONS IS NULL OR DBMS_LOB.INSTR(c.CONTENT_OPTIONS, '"showHighlight":') = 0);
UPDATE &S.POPUP_CONTENT c
   SET CONTENT_OPTIONS =
         REGEXP_REPLACE(c.CONTENT_OPTIONS, '^\s*\{', '{"showBottomDescription":'
             || CASE WHEN REGEXP_LIKE(c.CONTENT_OPTIONS, '"bottomDescription(Url)?":"\s*[^"[:space:]]') THEN 'true' ELSE 'false' END || ',', 1, 1),
       UPDATED_BY = 'CLEANUP', UPDATED_AT = CAST(SYSTIMESTAMP AT TIME ZONE 'Asia/Seoul' AS TIMESTAMP)
 WHERE c.POPUP_ID IN (SELECT POPUP_ID FROM &S.POPUP_NOTICE WHERE POPUP_TYPE = 'TEXT')
   AND DBMS_LOB.INSTR(c.CONTENT_OPTIONS, '"showBottomDescription":') = 0;
COMMIT;

PROMPT === 9. 제약: DISPLAY_MODE CHECK · 크기 NOT NULL · QUESTION_TYPE CHECK (이미 있으면 건너뜀) ===
DECLARE
    PROCEDURE run(p_sql VARCHAR2) IS
    BEGIN
        EXECUTE IMMEDIATE p_sql;
        DBMS_OUTPUT.PUT_LINE('OK   ' || p_sql);
    EXCEPTION
        WHEN OTHERS THEN
            -- ORA-02264 제약 이름 중복, ORA-02275 동일 제약 존재, ORA-01442 이미 NOT NULL
            IF SQLCODE IN (-2264, -2275, -1442) THEN
                DBMS_OUTPUT.PUT_LINE('SKIP ' || p_sql);
            ELSE
                RAISE;
            END IF;
    END;
BEGIN
    run('ALTER TABLE &S.POPUP_NOTICE ADD CONSTRAINT CK_POPUP_DISPLAY_MODE CHECK (DISPLAY_MODE IN (''SEQUENTIAL'', ''SIMULTANEOUS''))');
    run('ALTER TABLE &S.POPUP_NOTICE MODIFY (POPUP_WIDTH NOT NULL)');
    run('ALTER TABLE &S.POPUP_NOTICE MODIFY (POPUP_HEIGHT NOT NULL)');
    run('ALTER TABLE &S.POPUP_NOTICE MODIFY (WIDTH_RATIO NOT NULL)');
    run('ALTER TABLE &S.POPUP_NOTICE MODIFY (HEIGHT_RATIO NOT NULL)');
    run('ALTER TABLE &S.POPUP_NOTICE MODIFY (MINIMUM_WIDTH NOT NULL)');
    run('ALTER TABLE &S.POPUP_NOTICE MODIFY (MINIMUM_HEIGHT NOT NULL)');
    run('ALTER TABLE &S.POPUP_NOTICE MODIFY (MAXIMUM_WIDTH NOT NULL)');
    run('ALTER TABLE &S.POPUP_NOTICE MODIFY (MAXIMUM_HEIGHT NOT NULL)');
    run('ALTER TABLE &S.POPUP_QUESTION ADD CONSTRAINT CK_QUESTION_TYPE CHECK (QUESTION_TYPE IN (''SINGLE_CHOICE'', ''MULTIPLE_CHOICE'', ''TEXT''))');
END;
/
COMMENT ON TABLE  &S.POPUP_QUESTION IS '문항. QUESTION_TYPE: SINGLE_CHOICE / MULTIPLE_CHOICE / TEXT';
COMMENT ON COLUMN &S.POPUP_NOTICE.PASSING_SCORE IS 'QUIZ 통과 점수. QUIZ 팝업은 WPF 응답 최상위 passingScore로 내려줌(설계 12)';

